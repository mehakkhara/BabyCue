export const WHO = {
  weight: { boys: WEIGHT_BOYS, girls: WEIGHT_GIRLS },
  height: { boys: HEIGHT_BOYS, girls: HEIGHT_GIRLS },
}

export function getPercentile(month, value, sex, metric) {
  const data = WHO[metric][sex === 'M' ? 'boys' : 'girls']
  const m = Math.min(24, Math.max(0, Math.round(month)))
  const bands = [
    { p: 3,  val: data.p3[m]  },
    { p: 15, val: data.p15[m] },
    { p: 50, val: data.p50[m] },
    { p: 85, val: data.p85[m] },
    { p: 97, val: data.p97[m] },
  ]
  if (value <= bands[0].val) return 3
  if (value >= bands[4].val) return 97
  for (let i = 0; i < bands.length - 1; i++) {
    if (value >= bands[i].val && value <= bands[i + 1].val) {
      const t = (value - bands[i].val) / (bands[i + 1].val - bands[i].val)
      return Math.round(bands[i].p + t * (bands[i + 1].p - bands[i].p))
    }
  }
  return 50
}

export function ordinal(n) {
  const s = ['th', 'st', 'nd', 'rd']
  const v = n % 100
  return n + (s[(v - 20) % 10] || s[v] || s[0])
}

export function monthsBetween(dob, measureDate) {
  const start = new Date(dob)
  const end = new Date(measureDate)
  const months = (end.getFullYear() - start.getFullYear()) * 12 + (end.getMonth() - start.getMonth())
  const dayFraction = (end.getDate() - start.getDate()) / 30
  return Math.max(0, months + dayFraction)
}
